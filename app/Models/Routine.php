<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;

class Routine extends Model
{
    use HasFactory;

    protected $fillable = [
        'user_id',
        'trainer_assignment_id',
        'auto_generated',
        'name',
        'notes',
        'program_goal',
        'program_experience',
        'program_frequency',
        'est_duration_minutes',
    ];

    protected $casts = [
        'est_duration_minutes' => 'integer',
        'auto_generated' => 'boolean',
        'program_frequency' => 'integer',
    ];

    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /** True when produced by ProgramGenerator rather than written by a trainer. */
    public function isAutoGenerated(): bool
    {
        return $this->auto_generated;
    }

    /**
     * The trainer assignment that prescribed this routine, if any.
     * NULL means the member built it themselves.
     */
    public function trainerAssignment(): BelongsTo
    {
        return $this->belongsTo(TrainerAssignment::class);
    }

    /** Whether this routine was prescribed by a trainer. */
    public function isPrescribed(): bool
    {
        return $this->trainer_assignment_id !== null;
    }

    public function routineExercises(): HasMany
    {
        return $this->hasMany(RoutineExercise::class)->orderBy('order');
    }
}
